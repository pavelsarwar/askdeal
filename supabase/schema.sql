do $$ declare t text; begin
  foreach t in array array['states','categories','merchants','branches','products','product_prices','deals','gold_rates','remittance_rates','fuel_prices','hospitals','articles'] loop
    execute format('drop policy if exists "public read %s" on public.%I', t, t);
    execute format('create policy "public read %s" on public.%I for select to anon, authenticated using (true)', t, t);
  end loop;
end $$;

do $$ declare t text; begin
  foreach t in array array['states','categories','merchants','branches','products','product_prices','deals','gold_rates','remittance_rates','fuel_prices','hospitals','articles'] loop
    execute format('drop policy if exists "admin write %s" on public.%I', t, t);
    execute format('create policy "admin write %s" on public.%I for all to authenticated using ((select public.is_naps_admin())) with check ((select public.is_naps_admin()))', t, t);
  end loop;
end $$;

