create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  role text not null default 'editor' check (role in ('super_admin','admin','editor','merchant')),
  created_at timestamptz not null default now()
);

create or replace function public.is_naps_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role in ('super_admin','admin','editor'));
$$;

create table if not exists public.states (
  id bigint generated by default as identity primary key,
  name text unique not null,
  type text not null check (type in ('state','federal_territory')),
  slug text unique not null
);

