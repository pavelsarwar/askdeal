create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text unique not null, slug text unique not null, icon text, active boolean not null default true
);
create table if not exists public.merchants (
  id uuid primary key default gen_random_uuid(), name text not null, slug text unique not null,
  merchant_type text, logo_url text, website_url text, active boolean not null default true,
  created_at timestamptz not null default now()
);
create table if not exists public.branches (
  id uuid primary key default gen_random_uuid(), merchant_id uuid not null references public.merchants(id) on delete cascade,
  state_id bigint references public.states(id), name text not null, address text, city text,
  latitude numeric(10,7), longitude numeric(10,7), active boolean not null default true
);
create table if not exists public.products (
  id uuid primary key default gen_random_uuid(), category_id bigint references public.categories(id),
  name text not null, slug text unique not null, brand text, size_label text, barcode text,
  image_url text, description text, active boolean not null default true, created_at timestamptz not null default now()
);
create table if not exists public.product_prices (
  id uuid primary key default gen_random_uuid(), product_id uuid not null references public.products(id) on delete cascade,
  merchant_id uuid not null references public.merchants(id) on delete cascade, branch_id uuid references public.branches(id) on delete set null,
  state_id bigint references public.states(id), normal_price numeric(12,2), offer_price numeric(12,2) not null,
  offer_start timestamptz, offer_end timestamptz, source_url text, verified boolean not null default false,
  active boolean not null default true, updated_at timestamptz not null default now()
);
create index if not exists product_prices_product_idx on public.product_prices(product_id);
create index if not exists product_prices_state_idx on public.product_prices(state_id);
create index if not exists product_prices_offer_idx on public.product_prices(offer_price);

create table if not exists public.deals (
  id uuid primary key default gen_random_uuid(), merchant_id uuid references public.merchants(id), category_id bigint references public.categories(id),
  state_id bigint references public.states(id), title text not null, slug text unique not null, description text, image_url text,
  discount_text text, start_at timestamptz, end_at timestamptz, source_url text, published boolean not null default false,
  created_at timestamptz not null default now()
);
create table if not exists public.gold_rates (
  id uuid primary key default gen_random_uuid(), rate_date date not null, purity text not null,
  price_per_gram numeric(12,2) not null, merchant_name text, source_url text, created_at timestamptz not null default now()
);
create table if not exists public.remittance_rates (
  id uuid primary key default gen_random_uuid(), provider text not null, destination_country text not null,
  currency text not null, rate numeric(16,6) not null, transfer_fee numeric(12,2) default 0,
  payout_method text, source_url text, updated_at timestamptz not null default now()
);
create table if not exists public.fuel_prices (
  id uuid primary key default gen_random_uuid(), fuel_type text not null, price_per_litre numeric(8,3) not null,
  effective_from date not null, effective_to date, region text default 'Malaysia', source_url text,
  created_at timestamptz not null default now()
);
create table if not exists public.hospitals (
  id uuid primary key default gen_random_uuid(), name text not null, state_id bigint references public.states(id), city text,
  specialties text[], consultation_min numeric(12,2), consultation_max numeric(12,2), emergency_24h boolean default false,
  international_patient boolean default false, website_url text, active boolean not null default true
);
create table if not exists public.articles (
  id uuid primary key default gen_random_uuid(), title text not null, slug text unique not null,
  article_type text not null default 'how-to', excerpt text, content text, cover_url text,
  state_id bigint references public.states(id), published boolean not null default false,
  published_at timestamptz, created_at timestamptz not null default now()
);

